/* ============================================================================
 * js/utils.js —— 通用纯函数工具箱
 *
 * 【规矩】这里只放纯函数：同样的输入永远得到同样的输出。
 *   不许碰 DOM、不许读写全局状态、不许有副作用。
 *   随机数一律走传入的 rng 参数，本文件自己不留任何状态。
 *
 * 【为什么 d′ / 正态分布的计算必须集中在这里】
 *   见 CONTRACT.md 第 4.5 节：任何模块都不许自己实现 z() / dPrime。
 *   各写各的，早晚会算出不一样的结果。
 * ==========================================================================*/

window.Utils = (function () {
  'use strict';

  /* --------------------------------------------------------------------------
   * 0. 随机数适配层
   *
   * rng 形如 { next: function(){ return 0~1 } }。
   * 不传就用 Math.random 兜底 —— 这样模块可以先用随机数跑通，
   * 之后换成固定种子的 rng 就能复现同一批患者。
   * ------------------------------------------------------------------------ */

  function u(rng) {
    return (rng && typeof rng.next === 'function') ? rng.next() : Math.random();
  }

  /* --------------------------------------------------------------------------
   * 1. zScore(p) —— 逆正态 CDF（Acklam 近似）
   *
   * 给一个概率 p（0~1），返回标准正态分布下对应的 z 值。
   * 精度约 1.15e-9，对实验数据足够。
   *
   * 【为什么要它】SDT 的 d′ 和 c 都要把"击中率/误报率"反算成 z 值：
   *   dPrime = z(pH) - z(pFA)
   *   c      = -0.5 * (z(pH) + z(pFA))
   * ------------------------------------------------------------------------ */

  function zScore(p) {
    if (p <= 0) return -Infinity;
    if (p >= 1) return Infinity;

    var a = [-3.969683028665376e+01,  2.209460984245205e+02,
             -2.759285104469687e+02,  1.383577518672690e+02,
             -3.066479806614716e+01,  2.506628277459239e+00];
    var b = [-5.447609879822406e+01,  1.615858368580409e+02,
             -1.556989798598866e+02,  6.680131188771972e+01,
             -1.328068155288572e+01];
    var c = [-7.784894002430293e-03, -3.223964580411365e-01,
             -2.400758277161838e+00, -2.549732539343734e+00,
              4.374664141464968e+00,  2.938163982698783e+00];
    var d = [ 7.784695709041462e-03,  3.224671290700398e-01,
              2.445134137142996e+00,  3.754408661907416e+00];

    var pLow  = 0.02425;
    var pHigh = 1 - pLow;
    var q, r;

    // 左尾
    if (p < pLow) {
      q = Math.sqrt(-2 * Math.log(p));
      return (((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
             ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1);
    }

    // 右尾（镜像）
    if (p > pHigh) {
      q = Math.sqrt(-2 * Math.log(1 - p));
      return -(((((c[0] * q + c[1]) * q + c[2]) * q + c[3]) * q + c[4]) * q + c[5]) /
              ((((d[0] * q + d[1]) * q + d[2]) * q + d[3]) * q + 1);
    }

    // 中段
    q = p - 0.5;
    r = q * q;
    return (((((a[0] * r + a[1]) * r + a[2]) * r + a[3]) * r + a[4]) * r + a[5]) * q /
           (((((b[0] * r + b[1]) * r + b[2]) * r + b[3]) * r + b[4]) * r + 1);
  }

  /* --------------------------------------------------------------------------
   * 2. ncdf(x) —— 标准正态累积分布 P(Z <= x)
   *    用 erf 的 Abramowitz-Stegun 7.1.26 近似，绝对误差 < 1.5e-7。
   * ------------------------------------------------------------------------ */

  function erf(x) {
    var sign = x < 0 ? -1 : 1;
    var ax = Math.abs(x);
    var t = 1 / (1 + 0.3275911 * ax);
    var y = 1 - (((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t
                   - 0.284496736) * t + 0.254829592) * t) * Math.exp(-ax * ax);
    return sign * y;
  }

  function ncdf(x) {
    return 0.5 * (1 + erf(x / Math.SQRT2));
  }

  /* --------------------------------------------------------------------------
   * 3. npdf(x, m, s) —— 均值 m、标准差 s 的正态概率密度
   *    实验室的"两个分布"面板要靠它画曲线。
   * ------------------------------------------------------------------------ */

  function npdf(x, m, s) {
    m = (m === undefined) ? 0 : m;
    s = (s === undefined) ? 1 : s;
    var z = (x - m) / s;
    return Math.exp(-0.5 * z * z) / (s * Math.sqrt(2 * Math.PI));
  }

  /* --------------------------------------------------------------------------
   * 4. randN(m, s) —— Box-Muller 正态随机数
   *    u1 取不到 0（log(0) 会炸），所以用 1 - u 把它挤到 (0, 1]。
   * ------------------------------------------------------------------------ */

  function randN(m, s, rng) {
    m = (m === undefined) ? 0 : m;
    s = (s === undefined) ? 1 : s;
    var u1 = 1 - u(rng);
    var u2 = u(rng);
    var z = Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
    return m + s * z;
  }

  /* --------------------------------------------------------------------------
   * 5. 小工具
   * ------------------------------------------------------------------------ */

  // 把 v 夹在 [lo, hi] 之间
  function clamp(v, lo, hi) {
    return v < lo ? lo : (v > hi ? hi : v);
  }

  // 保留一位小数（体温、d′、c 都要用）
  function round1(x) {
    return Math.round(x * 10) / 10;
  }

  // 随机取一个元素，不传 rng 就用 Math.random
  function pick(arr, rng) {
    return arr[Math.floor(u(rng) * arr.length)];
  }

  // Fisher-Yates 洗牌，返回【新数组】，不改动传入的数组
  function shuffle(arr, rng) {
    var out = arr.slice();
    for (var i = out.length - 1; i > 0; i--) {
      var j = Math.floor(u(rng) * (i + 1));
      var t = out[i];
      out[i] = out[j];
      out[j] = t;
    }
    return out;
  }

  // 平均数，空数组返回 0
  function mean(arr) {
    if (!arr || arr.length === 0) return 0;
    var sum = 0;
    for (var i = 0; i < arr.length; i++) sum += arr[i];
    return sum / arr.length;
  }

  /* ------------------------------------------------------------------------ */

  return {
    zScore: zScore,
    ncdf: ncdf,
    npdf: npdf,
    randN: randN,
    clamp: clamp,
    round1: round1,
    pick: pick,
    shuffle: shuffle,
    mean: mean,
    rand01: u,   // 0~1 均匀数适配器（randN / pick 内部用的就是它，各模块也直接用）
  };

})();
